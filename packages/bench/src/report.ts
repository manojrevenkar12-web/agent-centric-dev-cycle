/** Summarise benchmark runs: per setup, how often the change was right, green, mergeable and honest,
 * what it cost, and a paired comparison of each model with and without n8n's agent instructions. */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, loadConfig } from "@acdc/core";
import { wilson } from "./risk-train.js";
import { RUNS, type RunResult, type Setup, spent } from "./run.js";
import { readTasks } from "./tasks.js";

export function loadRuns(): RunResult[] {
  if (!existsSync(RUNS)) return [];
  return readdirSync(RUNS, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .flatMap((d) =>
      readdirSync(join(RUNS, d.name))
        .filter((f) => f.endsWith(".json"))
        .map((f) => JSON.parse(readFileSync(join(RUNS, d.name, f), "utf8")) as RunResult),
    );
}

/** Exact two-sided sign test on discordant pairs (McNemar). */
export function signTest(b: number, c: number): number {
  const n = b + c;
  if (!n) return 1;
  const k = Math.min(b, c);
  let p = 0;
  let coef = 1;
  for (let i = 0; i <= n; i++) {
    if (i > 0) coef = (coef * (n - i + 1)) / i;
    if (i <= k) p += coef;
  }
  return Math.min(1, (2 * p) / 2 ** n);
}

const median = (xs: number[]) => {
  const s = [...xs].sort((a, b) => a - b);
  return s.length ? (s[Math.floor((s.length - 1) / 2)] ?? 0) : 0;
};

export function summarise(runs: RunResult[], setups: Setup[]) {
  const per = setups.map((s) => {
    const rs = runs.filter((r) => r.setup === s.name);
    const n = rs.length;
    const k = (f: (r: RunResult) => boolean) => rs.filter(f).length;
    const resolved = k((r) => !!r.grade?.resolved);
    const cost = rs.reduce((a, r) => a + r.session.cost_usd, 0);
    return {
      setup: s.name,
      model: s.model,
      context: s.context,
      runs: n,
      resolved,
      resolved_rate: n ? resolved / n : 0,
      resolved_ci95: wilson(resolved, n),
      ci_pass_rate: n ? k((r) => !!r.grade?.ci_pass) / n : 0,
      mergeable_rate: n ? k((r) => !!r.grade?.mergeable) / n : 0,
      self_verified_rate: n ? k((r) => r.session.tests_run > 0) / n : 0,
      overclaim_rate: n ? k((r) => !!r.grade?.claim.overclaim) / n : 0,
      outside_package: k((r) => (r.grade?.outside_package.length ?? 0) > 0),
      added_tests_rate: n ? k((r) => (r.grade?.test_files_changed.length ?? 0) > 0) / n : 0,
      lines_vs_reference: median(
        rs.map((r) => (r.grade?.lines_changed ?? 0) / Math.max(1, r.grade?.reference_lines ?? 1)),
      ),
      errors: k((r) => !r.session.ok),
      denials: rs.reduce((a, r) => a + r.session.denials, 0),
      cost_usd: cost,
      cost_per_resolved_usd: resolved ? cost / resolved : null,
      median_seconds: median(rs.map((r) => r.session.seconds)),
      levels: rs.reduce<Record<string, number>>((m, r) => {
        const l = r.grade?.policy.level ?? "none";
        m[l] = (m[l] ?? 0) + 1;
        return m;
      }, {}),
    };
  });
  const models = [...new Set(setups.map((s) => s.model))];
  const paired = models.flatMap((m) => {
    const repo = setups.find((s) => s.model === m && s.context === "repo");
    const bare = setups.find((s) => s.model === m && s.context === "bare");
    if (!repo || !bare) return [];
    const a = new Map(runs.filter((r) => r.setup === repo.name).map((r) => [r.task, !!r.grade?.resolved]));
    const b = new Map(runs.filter((r) => r.setup === bare.name).map((r) => [r.task, !!r.grade?.resolved]));
    const both = [...a.keys()].filter((t) => b.has(t));
    const onlyRepo = both.filter((t) => a.get(t) && !b.get(t)).length;
    const onlyBare = both.filter((t) => !a.get(t) && b.get(t)).length;
    return [
      {
        model: m,
        tasks: both.length,
        only_with_agents_md: onlyRepo,
        only_without: onlyBare,
        p_value: signTest(onlyRepo, onlyBare),
      },
    ];
  });
  return { per, paired };
}

const pct = (x: number) => `${(100 * x).toFixed(0)}%`;

export function writeReport() {
  const setups = loadConfig<{ run: { setups: Setup[] } }>("bench").run.setups;
  const runs = loadRuns();
  const tasks = readTasks();
  const s = summarise(runs, setups);
  const out = { tasks: tasks.length, spent_usd: spent(), ...s };
  writeFileSync(join(ROOT, "reports/bench.json"), `${JSON.stringify(out, null, 2)}\n`);
  const risk = JSON.parse(readFileSync(join(ROOT, "reports/risk.json"), "utf8"));
  const md = [
    "# Results",
    "",
    "Generated by `pnpm acdc report` from reports/runs/, reports/risk.json and data/tasks/tasks.json. Do not edit.",
    "",
    `## Benchmark: ${tasks.length} real n8n fixes, each setup once`,
    "",
    "| Setup | Runs | Resolved | 95% CI | CI green | Mergeable | Ran tests itself | Said pass, wasn't | Cost | Cost per resolved |",
    "|---|---|---|---|---|---|---|---|---|---|",
    ...s.per.map(
      (p) =>
        `| ${p.setup} | ${p.runs} | ${p.resolved} (${pct(p.resolved_rate)}) | ${pct(p.resolved_ci95[0])}–${pct(p.resolved_ci95[1])} | ${pct(p.ci_pass_rate)} | ${pct(p.mergeable_rate)} | ${pct(p.self_verified_rate)} | ${pct(p.overclaim_rate)} | $${p.cost_usd.toFixed(2)} | ${p.cost_per_resolved_usd === null ? "–" : `$${p.cost_per_resolved_usd.toFixed(2)}`} |`,
    ),
    "",
    "With and without n8n's AGENTS.md (same tasks, same model):",
    "",
    "| Model | Tasks | Resolved only with AGENTS.md | Resolved only without | Sign test p |",
    "|---|---|---|---|---|",
    ...s.paired.map(
      (p) =>
        `| ${p.model} | ${p.tasks} | ${p.only_with_agents_md} | ${p.only_without} | ${p.p_value.toFixed(2)} |`,
    ),
    "",
    `Spent on agents: $${spent().toFixed(2)}.`,
    "",
    "## Change risk on n8n's history",
    "",
    `${risk.data.merged_changes} merged changes since ${risk.data.train ? "November 2025" : ""}; ${pct(risk.data.bad_rate)} needed a revert or a follow-up fix within a week. Trained on changes up to ${risk.data.train.until}, tested on ${risk.data.test.changes} later changes (${risk.data.test.from} to ${risk.data.test.to}).`,
    "",
    `- AUC ${risk.test.auc.toFixed(3)} (size-and-tests rule: ${risk.test.auc_naive_rule.toFixed(3)}); without the file-history feature ${risk.ablation_without_file_history.auc.toFixed(3)}; calibration error ${risk.test.ece.toFixed(3)}.`,
    "",
    "| Share approved without a person | Bad changes let through: model | Size-and-tests rule |",
    "|---|---|---|",
    ...risk.test.shadow.map(
      (x: {
        share: number;
        model: { rate: number; bad: number; changes: number };
        naive_rule: { rate: number; bad: number };
      }) =>
        `| ${pct(x.share)} | ${pct(x.model.rate)} (${x.model.bad} of ${x.model.changes}) | ${pct(x.naive_rule.rate)} (${x.naive_rule.bad}) |`,
    ),
    "",
    "The whole safety model replayed on the test months:",
    "",
    "| Level | Share of changes | Needed a revert or follow-up |",
    "|---|---|---|",
    ...Object.entries(risk.test.policy.levels).map(
      ([l, v]) =>
        `| ${l.replace("_", " ")} | ${pct((v as { share: number }).share)} | ${pct((v as { bad_rate: number }).bad_rate)} |`,
    ),
    "",
  ];
  writeFileSync(join(ROOT, "reports/RESULTS.md"), md.join("\n"));
  return out;
}
